
export function getColor(id) {

    switch (id) {
        case 1:
        return "#60B569";
    
        case 2:
        return "#53286B";
    
        case 3:
        return "#173A79";
    
        case 4:
        return "#A43956";
    
        default:
        return "#173A79";
    }

 }

